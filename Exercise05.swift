// Exercise 05 - Strings and String Interpolation

// Combining strings
let firstName = "Kamal"
let lastName = "Perera"
let fullName = firstName + " " + lastName
print(fullName)
// Output: Kamal Perera

// String interpolation
let name = "Kamal"
let age = 22
print("My name is \(name) and I am \(age) years old.")
// Output: My name is Kamal and I am 22 years old.

// Try This
let module = "SE4041"
let mark = 78
print("The student received \(mark) marks for \(module).")
// Output: The student received 78 marks for SE4041.

